package org.unigrid.hedgehog.model.crypto;

/* The account that pays for the checks of a spork has none left (CheckMeter): no answer about the spork, which is
   checked again when it comes again */
public class ChecksSpentException extends RuntimeException {
	private static final long serialVersionUID = 1L;

	public ChecksSpentException() {
		super("The checks that the source of the spork can pay for are spent", null, false, false);
	}
}
