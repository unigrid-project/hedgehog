package org.unigrid.hedgehog.proxy.session;

public enum Direction {
	CLIENT_TO_EXIT(1), EXIT_TO_CLIENT(2);

	private final byte code;

	Direction(int code) {
		this.code = (byte) code;
	}

	public byte code() {
		return code;
	}

	public Direction reverse() {
		return this == CLIENT_TO_EXIT ? EXIT_TO_CLIENT : CLIENT_TO_EXIT;
	}
}
